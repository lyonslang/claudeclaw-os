# Expected: wal
# If not WAL mode, the bot startup migration didn't run — restart bot

# 12.5 — Memory decay not running
sqlite3 store/claudeclaw.db "SELECT COUNT(*) FROM memories WHERE salience < 0.1 AND pinned = 0;"
# If high count: decay is working but cleanup isn't. Restart bot process.

# 12.6 — Dashboard won't load
curl -s http://localhost:3141/api/health
# Check: DASHBOARD_TOKEN set? DASHBOARD_PORT=3141 not in use?

# 12.7 — TypeScript won't compile
