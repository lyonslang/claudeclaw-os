# 12.3 — YouTube Analytics returns 403
# Check: OAuth token expired? Re-run: npx tsx scripts/yt-analytics-auth.ts
# Check: "YouTube Analytics API" enabled in Google Cloud project?

# 12.4 — Database locked errors
