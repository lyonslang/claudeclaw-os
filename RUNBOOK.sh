sqlite3 store/claudeclaw.db "SELECT COALESCE('$' || ROUND(SUM(cost_usd), 2), '\$0.00') || ' across ' || COUNT(*) || ' turns' FROM token_usage WHERE created_at >= strftime('%s', 'now', 'start of day');" && \
echo "" && \
echo "--- Scheduled Tasks ---" && \
sqlite3 store/claudeclaw.db "SELECT status, COUNT(*) FROM scheduled_tasks GROUP BY status;" && \
echo "" && \
echo "--- Missions ---" && \
sqlite3 store/claudeclaw.db "SELECT status, COUNT(*) FROM mission_tasks GROUP BY status;" && \
echo "" && \
echo "=== STATUS CHECK COMPLETE ==="

# ─────────────────────────────────────────────────────────────────────────────
# SECTION 12: TROUBLESHOOTING
# ─────────────────────────────────────────────────────────────────────────────

