sqlite3 store/claudeclaw.db "SELECT 'YouTube videos: ' || COUNT(*) FROM youtube_videos;" && \
sqlite3 store/claudeclaw.db "SELECT 'Channel snapshots: ' || COUNT(*) FROM channel_snapshots;" && \
sqlite3 store/claudeclaw.db "SELECT 'Hive Mind entries: ' || COUNT(*) FROM hive_mind;" && \
sqlite3 store/claudeclaw.db "SELECT 'Memories: ' || COUNT(*) || ' (pinned: ' || SUM(CASE WHEN pinned=1 THEN 1 ELSE 0 END) || ')' FROM memories;" && \
